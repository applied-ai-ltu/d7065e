"""Render k8s/edge.yaml: one Deployment per (floor, role), pinned to its node.

Active controllers run on the Raspberry Pi; standbys on infinity-magic with an
identical pod spec, so a promoted standby behaves exactly like the active it replaces.
"""

from pathlib import Path

NAMESPACE = "ai-edge-intel-course"
FLOORS = ["level0", "level1", "level2"]
NODES = {"active": "pi400-master-01", "standby": "infinity-magic"}
IMAGE = "fds-edge:latest"

TEMPLATE = """\
apiVersion: apps/v1
kind: Deployment
metadata:
  name: edge-{floor}-{role}
  namespace: {ns}
  labels: {{app: fds-edge, tier: edge, floor: {floor}, role: {role}}}
spec:
  replicas: 1
  strategy: {{type: Recreate}}
  selector:
    matchLabels: {{app: fds-edge, floor: {floor}, role: {role}}}
  template:
    metadata:
      labels: {{app: fds-edge, tier: edge, floor: {floor}, role: {role}}}
    spec:
      nodeSelector:
        kubernetes.io/hostname: {node}
      terminationGracePeriodSeconds: 5
      containers:
        - name: edge
          image: {image}
          imagePullPolicy: Never
          args: ["--floor", "{floor}", "--role", "{role}"]
          env:
            - {{name: MQTT_BROKER, value: "mosquitto.data-infra.svc.cluster.local"}}
            - {{name: MQTT_PORT, value: "1883"}}
            - {{name: BUILDSIM_URL, value: "http://buildsim.{ns}.svc.cluster.local:9090"}}
            - name: NODE_NAME
              valueFrom: {{fieldRef: {{fieldPath: spec.nodeName}}}}
          resources:
            requests: {{cpu: 150m, memory: 192Mi}}
            limits: {{cpu: "1", memory: 1Gi}}
"""


def main():
    docs = [
        TEMPLATE.format(floor=f, role=r, node=n, ns=NAMESPACE, image=IMAGE)
        for f in FLOORS
        for r, n in NODES.items()
    ]
    out = Path(__file__).with_name("edge.yaml")
    out.write_text("# Generated by render_edge.py — do not edit by hand.\n" + "---\n".join(docs))
    print(f"wrote {out} ({len(docs)} deployments)")


if __name__ == "__main__":
    main()
